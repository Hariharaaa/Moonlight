import { findDeployedContract } from '@midnight-ntwrk/midnight-js-contracts';
import { httpClientProofProvider } from '@midnight-ntwrk/midnight-js-http-client-proof-provider';
import { indexerPublicDataProvider } from '@midnight-ntwrk/midnight-js-indexer-public-data-provider';
import { levelPrivateStateProvider } from '@midnight-ntwrk/midnight-js-level-private-state-provider';
import { FetchZkConfigProvider } from '@midnight-ntwrk/midnight-js-fetch-zk-config-provider';
import { CompiledContract } from '@midnight-ntwrk/midnight-js-protocol/compact-js';
import type { ConnectedAPI } from '@midnight-ntwrk/dapp-connector-api';
import { config as networkConfig, CONTRACT_ADDRESS } from '../config/network';
import { PRIVATE_STATE_ID } from '../hooks/usePrivateState';

// In Vite, we've aliased 'managed' to our contract output directory.
// The index.js is generated by the Compact compiler.
import * as CounterContract from 'managed/contract';

export async function createProviders(walletApi: ConnectedAPI) {
  // Get wallet configuration directly from the DApp connector
  const serviceUris = await walletApi.getConfiguration();
  const shielded = await walletApi.getShieldedAddresses();
  const unshielded = await walletApi.getUnshieldedAddress();

  const coinPublicKey = shielded.shieldedCoinPublicKey;
  const encryptionPublicKey = shielded.shieldedEncryptionPublicKey;

  // Wallet provider implementation that delegates to the DApp Connector
  const walletProvider = {
    getCoinPublicKey: () => coinPublicKey,
    getEncryptionPublicKey: () => encryptionPublicKey,
    balanceTx: async (tx: any) => {
      const balanced = await walletApi.balanceUnsealedTransaction(tx);
      // Wait, balanceUnsealedTransaction returns { tx: string }. Is this what WalletProvider expects?
      // For Midnight.js 4.1.x, often the transaction strings are used directly.
      // If it expects a specific object, we might need to map it. Let's return balanced.tx for now or the object.
      // According to the types, it returns FinalizedTransaction. If it's a string, we just return the string.
      return balanced.tx as any; 
    },
    submitTx: async (tx: any) => walletApi.submitTransaction(tx),
  };

  // ZK Config Provider fetches the proving/verifying keys and ZKIR from the static assets we serve
  const zkConfigProvider = new FetchZkConfigProvider(window.location.origin, fetch.bind(window));

  return {
    // 1. Private State Provider (Local Browser Storage)
    privateStateProvider: levelPrivateStateProvider({
      privateStateStoreName: 'counter-private-state',
      accountId: unshielded.unshieldedAddress,
      privateStoragePasswordProvider: async () => 'midnight-demo-password', 
    }),

    // 2. Public Data Provider (Indexer)
    publicDataProvider: indexerPublicDataProvider(
      serviceUris.indexerUri || networkConfig.indexer,
      serviceUris.indexerWsUri || networkConfig.indexerWS
    ),

    // 3. ZK Config Provider
    zkConfigProvider,

    // 4. Proof Provider
    proofProvider: httpClientProofProvider(
      serviceUris.proverServerUri || networkConfig.proofServer,
      zkConfigProvider
    ),

    // 5. Wallet Provider
    walletProvider,
    midnightProvider: walletProvider,
  };
}

export async function getContractInstance(walletApi: ConnectedAPI) {
  const providers = await createProviders(walletApi);

  const compiledContract = CompiledContract.make('counter', CounterContract.Contract).pipe(
    CompiledContract.withVacantWitnesses
  );

  const deployed = await findDeployedContract(providers as any, {
    compiledContract: compiledContract as any,
    contractAddress: CONTRACT_ADDRESS,
    privateStateId: PRIVATE_STATE_ID,
  });

  return {
    deployed,
    providers,
  };
}
